// The 7 topics of the videos. The visible name of each topic is in `ui.topics` (per language).
export type VideoTopic = 'goodnews' | 'jesus' | 'science' | 'morality' | 'suffering' | 'religions' | 'bible';

export interface VideoItem {
  id: string;
  youtubeId: string;
  title: string;
  topic: VideoTopic;
  source: string; // YouTube channel name (a name, not translated)
  featured?: boolean; // true = shown on the main page (exactly 3 videos)
  long?: boolean; // true = shows the "Long video" tag
}

export interface ApologeticItem {
  id: string;
  worldview: 'islam' | 'atheism' | 'hinduism' | 'judaism';
  question: string;
  shortAnswer: string;
  detailedAnswer: string;
  keyScriptures: string[];
  recommendedThinkers: string[];
}

export interface ResourceArticle {
  id: string;
  title: string;
  category: string;
  readTime: string;
  summary: string;
  content: string[];
  scriptureReferences: string[];
}

